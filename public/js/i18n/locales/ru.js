  // Drink names in Russian are built differently from English:
  //   English "Taro oolong tea"  ->  Русский "Улун с таро"  (tea + «с» + flavor, instrumental case)
  grammar: {
    drinkName(drink, L) {
      const withFlavor = {
        classic: 'молоком',
        'brown-sugar': 'коричневым сахаром',
        taro: 'таро',
        strawberry: 'клубникой',
        mango: 'манго',
        passion: 'маракуйей',
        lychee: 'личи',
        peach: 'персиком',
        osmanthus: 'османтусом',
        coconut: 'кокосом',
      }[drink.flavor];
      return withFlavor ? `${L.tea(drink.tea)} с ${withFlavor}` : L.tea(drink.tea);
    },

    // "Сладость 50%, с тапиокой и сырной пенкой"
    orderDetails(drink) {
      const withTopping = {
        tapioca: 'тапиокой',
        popping: 'поппинг-бобой',
        'grass-jelly': 'травяным желе',
        'lychee-jelly': 'желе из личи',
        pudding: 'яичным пудингом',
        'red-bean': 'красной фасолью',
        'cheese-foam': 'сырной пенкой',
      };
      const sweet = `Сладость ${drink.sweet}%`;
      const names = drink.toppings.map((id) => withTopping[id]).filter(Boolean);
      if (names.length === 0) return `${sweet}, без топпингов`;
      const list = names.length === 1 ? names[0] : `${names.slice(0, -1).join(', ')} и ${names[names.length - 1]}`;
      return `${sweet}, с ${list}`;
    },
  },
